package android.graphics;

/** JVM harness stub: fields assigned by the constructor as the android.jar stub does. */
public class Rect {

    public int left;
    public int top;
    public int right;
    public int bottom;

    public Rect() {}

    public Rect(int left, int top, int right, int bottom) {
        this.left = left;
        this.top = top;
        this.right = right;
        this.bottom = bottom;
    }
}
